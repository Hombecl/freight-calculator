import assert from 'node:assert/strict';
import {packWithConstraints} from '../src/lib/binPacking.ts';
import {reviewPlanner,plannerRevision,sourceSpec} from '../src/lib/plannerReview.ts';
import {buildPlannerReport,plannerManifestCSV} from '../src/lib/plannerReport.ts';
import {snapshotChanges,snapshotRevision,validSnapshot} from '../src/lib/plannerHistory.ts';
import {plannerTransferPOs} from '../src/lib/workflowTransfer.ts';
import {feedbackAnswerMeta} from '../src/lib/exportFeedback.ts';
import {consolidate} from '../src/lib/consolidation.ts';
const c={l:100,w:100,h:200,maxWeight:200};
const s={id:'sku-a',label:'Same name',l:100,w:100,h:50,weight:10,qty:2,color:0xff0000,keepUpright:true,maxStack:15};
const packed=packWithConstraints(c,[s]);assert.equal(packed.boxes.length,2);
assert.ok(reviewPlanner(packed.boxes,c,[s]).complete);
const upper=packed.boxes.find(b=>b.py>0),base=packed.boxes.find(b=>b.py===0);
assert.ok(reviewPlanner([upper],c,[s]).issues.some(i=>i.code==='support'));
assert.ok(reviewPlanner([{...base,px:50},upper],{...c,l:150},[s]).issues.some(i=>i.code==='support'));
assert.ok(reviewPlanner(packed.boxes,c,[{...s,maxStack:0}]).issues.some(i=>i.code==='stack'));
assert.ok(reviewPlanner([{...upper,py:25},base],c,[s]).issues.some(i=>i.code==='overlap'));
assert.ok(reviewPlanner([{...base,px:-1}],c,[s]).issues.some(i=>i.code==='bounds'));
assert.ok(reviewPlanner([{...base,l:50,h:100}],c,[s]).issues.some(i=>i.code==='orientation'));
assert.ok(reviewPlanner(packed.boxes,{...c,maxWeight:15},[s]).issues.some(i=>i.code==='payload'));
assert.ok(reviewPlanner([base],c,[s],{w:90,h:40}).issues.some(i=>i.code==='door'));
assert.ok(!reviewPlanner(packed.boxes,c).complete);
assert.equal(sourceSpec({...base,specId:undefined},[s])?.id,s.id);
const second={...s,id:'sku-b',qty:1};
let reviewed=reviewPlanner([base],c,[s,second]);assert.deepEqual(reviewed.cargo.map(x=>[x.id,x.placed,x.remaining]),[['sku-a',1,1],['sku-b',0,1]]);
assert.ok(reviewPlanner([base,{...base,id:'other'}],c,[{...s,qty:1}]).issues.some(i=>i.code==='identity'));
const stacked=[{...base,id:'a',py:0},{...base,id:'b',py:50},{...base,id:'c',py:100}];
assert.ok(reviewPlanner(stacked,c,[{...s,qty:3}]).issues.some(i=>i.code==='stack'&&i.ids.includes('a')));
const o={meta:{title:'Test',containerLabel:'Test',container:c,unit:'cm',date:'2026-10-21'},boxes:[upper],requestedSpecs:[s,second],reportReference:'Job <script>',revision:'v1'};
for(const reportView of ['summary','crew','manifest']){
 const html=buildPlannerReport({...o,reportView});assert.ok(html.includes('DRAFT'));assert.ok(html.includes('60%'));assert.ok(html.includes('sku-b'));assert.ok(!html.includes('Job <script>'));assert.ok(html.includes('Job &lt;script&gt;'));assert.ok(!html.includes('Balanced'));
 assert.equal(html.includes('<svg'),reportView==='crew');
}
assert.ok(buildPlannerReport({...o,zh:true}).includes('草稿'));
const csv=plannerManifestCSV(o);assert.ok(csv.includes('"sku-b","Same name","1","0","1"'));assert.ok(csv.includes('"issue"'));assert.ok(csv.includes('draft_review'));
assert.ok(plannerManifestCSV({...o,reportReference:'=1+1'}).includes("'=1+1"));
const snapshot={jobId:'job',name:'one',containerKey:'20gp',overhangCm:0,specs:[s],boxes:packed.boxes,revision:'r',savedAt:'2026-10-21'};
assert.ok(validSnapshot(snapshot));assert.ok(!validSnapshot({...snapshot,boxes:[{...base,px:NaN}]}));
assert.notEqual(snapshotRevision(snapshot),snapshotRevision({...snapshot,boxes:[base]}));assert.equal(snapshotChanges(snapshot,{...snapshot,specs:[{...s,qty:4}]}).cargoRows,1);
assert.equal(plannerRevision({a:1}),plannerRevision({a:1}));
const transfer={orderId:'job',revision:'v',model:'loose-cartons',specs:[{...s,group:'PO1',allowRotate:false,unloadOrder:3},{...second,group:'PO2',keepUpright:undefined}]};
const pos=plannerTransferPOs(transfer);assert.equal(pos.length,2);assert.equal(pos[0].items[0].allowRotate,false);assert.equal(pos[1].items[0].keepUpright,false);
// Deliberately wide cargo fits only if illegal yaw is introduced. Comparison must preserve no-rotate.
const fixed={...s,id:'fixed',l:100,w:240,h:50,qty:1,allowRotate:false};
const compare=await consolidate({pos:plannerTransferPOs({...transfer,specs:[fixed]}),containers:[{preset:'20gp',maxCount:1}],rules:{unloadOrderByPo:false}});
assert.ok(compare.plans.every(p=>p.remainder.cartons===1));
assert.equal(feedbackAnswerMeta('planner','pdf','usefulness','edit'),'p:pdf:edit');
assert.equal(feedbackAnswerMeta('planner','pdf','recipient','private@email.com'),null);
assert.equal(feedbackAnswerMeta('planner','pdf','choice','gap'),'p:pdf:gap');
console.log('Planner review: support/stack propagation, reconciliation, draft reports, revisions, constrained transfer and categorical feedback passed');
